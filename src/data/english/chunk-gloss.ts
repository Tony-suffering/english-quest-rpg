/**
 * 活用形から原形の候補を出す。
 *
 * 以前は手書きの対応表(INFLECT)だけを見ていたが、表に無い動詞は素通りだった。
 * 動詞を列挙するやり方はどう頑張っても抜けるので、綴りの規則で作る。
 * 表のほうは不規則変化(went / took)のために残す。
 *
 * 候補を複数返して、どれかが辞書に当たればよい、という使い方をする。
 * 存在しない綴りが混ざっても、辞書に無ければ黙って外れるだけなので害がない。
 */
function baseForms(v: string): string[] {
    const out: string[] = [];
    if (INFLECT[v]) out.push(INFLECT[v]);
    if (v.endsWith('ing')) {
        const stem = v.slice(0, -3);
        out.push(stem, stem + 'e');
        // running -> run。同じ子音が重なっていたら1つ落とす
        if (stem.length > 2 && stem[stem.length - 1] === stem[stem.length - 2]) out.push(stem.slice(0, -1));
    }
    if (v.endsWith('ied')) out.push(v.slice(0, -3) + 'y');
    else if (v.endsWith('ed')) {
        const stem = v.slice(0, -2);
        out.push(stem, v.slice(0, -1));
        if (stem.length > 2 && stem[stem.length - 1] === stem[stem.length - 2]) out.push(stem.slice(0, -1));
    }
    if (v.endsWith('ies')) out.push(v.slice(0, -3) + 'y');
    else if (v.endsWith('es')) out.push(v.slice(0, -2), v.slice(0, -1));
    else if (v.endsWith('s') && !v.endsWith('ss')) out.push(v.slice(0, -1));
    return out;
}

export function glossFor(text: string): Gloss | undefined {
    const hit = CHUNK_GLOSS[text];
    if (hit) return hit;
    const w = text.split(' ');
    for (const base of baseForms(w[0])) {
        const alt = CHUNK_GLOSS[[base, ...w.slice(1)].join(' ')];
        if (alt) return alt;
    }
    // 可変枠: take care of ~ の訳を take care of him にも当てる
    if (!text.endsWith(' ~')) {
        for (let k = w.length - 1; k >= 2; k--) {
            const slot = CHUNK_GLOSS[w.slice(0, k).join(' ') + ' ~'];
            if (slot) return slot;
        }
    }
    return undefined;
}

// THE HUNDRED: 読めば中学英語。聞けば別言語。
// 「なぜ英語が聞こえないか」を100の音声現象に分解し、1現象=1例文で潰す。
// 1文で4技能(読む/聞く/音読/書く)を回すが、背骨はリスニング。
//
// 構成の根拠:
// - 弱形40語: Roach (2000) English Phonetics and Phonology の弱形語リスト
// - 機能語が聞こえない実証: Field (2008) TESOL Quarterly "Bricks or Mortar"
// - 日本人固有の知覚バイアス: Dupoux et al. (1999) 幻聴母音 / 野澤(立命館) m-n-ng実験
// - 音素対比の絞り込み: Munro & Derwing (2006) functional load
//   → th は低FLなので#100の1本だけ(逆張り枠)

export type HundredPart =
    | 'weak'       // 1-40 弱形
    | 'connected'  // 41-62 連結・脱落・同化
    | 'ears'       // 63-74 日本人の耳(知覚バイアス)
    | 'prosody'    // 75-86 プロソディ
    | 'endings'    // 87-96 語尾と数字
    | 'pairs';     // 97-100 高FL対比

export interface HundredLine {
    /** 話者名 */
    sp: string;
    line: string;
    /** 崩れた実音 */
    sound: string;
    ja: string;
    /** この行が狙いの現象を含むターゲット行か */
    target: boolean;
}

export interface HundredEntry {
    no: number;
    key: string;
    part: HundredPart;
    phenomenon: string;
    sentence: string;
    sound: string;
    ja: string;
    focus: string;
    trap: string;
    extras: string[];
    scene: string;
    /**
     * 3行の掛け合い。1行フラッシュカードだと読んでいてつまらず、
     * 録音する講師も単調になって「きれいに読む」事故が起きる。
     * 場面を演じさせると崩れた音が自然に出る。
     */
    dialogue?: HundredLine[];
    /** キャラ名なしで、読者が明日そのまま使える汎用文 */
    youVersion?: string;
    /** この場面に副次的に含まれる現象(主ターゲット100の穴埋め) */
    alsoCovers?: string[];
}


export function getPartForNo(no: number): HundredPart {
    if (no <= 40) return 'weak';
    if (no <= 62) return 'connected';
    if (no <= 74) return 'ears';
    if (no <= 86) return 'prosody';
    if (no <= 96) return 'endings';
    return 'pairs';
}


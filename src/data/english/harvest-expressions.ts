/**
 * Seed harvest expressions into localStorage if not already present.
 * Call this on page mount before loading expressions.
 */
export function seedHarvestExpressions(): void {
    if (typeof window === 'undefined') return;
    const key = 'harvest-expressions';
    const existing = localStorage.getItem(key);
    if (existing) {
        // Merge: add any new seed expressions that don't exist yet
        try {
            const parsed: HarvestExpression[] = JSON.parse(existing);
            const existingIds = new Set(parsed.map(e => e.id));
            const newExprs = HARVEST_EXPRESSIONS.filter(e => !existingIds.has(e.id));
            if (newExprs.length > 0) {
                localStorage.setItem(key, JSON.stringify([...parsed, ...newExprs]));
            }
        } catch {
            // Corrupted data, overwrite
            localStorage.setItem(key, JSON.stringify(HARVEST_EXPRESSIONS));
        }
        return;
    }
    localStorage.setItem(key, JSON.stringify(HARVEST_EXPRESSIONS));
}

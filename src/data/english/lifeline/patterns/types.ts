/**
 * THE PATTERN SPINE — 層1。この教材の背骨。
 *
 * ■ なぜこれが要るか(2026-08-07 の設計変更)
 * それまでの実装は「文の在庫」だった。窓口ごとに実例を集めて積む方式で、
 * 2万文集めても **覚えた文しか出てこない**。認識には効くが産出には効かない。
 * フレーズブックを厚くしているだけで、ネイティブには一生届かない。
 *
 * 話者が実際に持っているのは文の一覧ではなく、**スロット付きの型**の在庫と、
 * そこに刺す語彙である。型そのものは会話を回すぶんなら千数百のオーダーで有限。
 * スロットに入る中身が数万。**有限の型 × 大量の充填** の掛け算になっている。
 *
 * ■ 3層
 *   層1  型      本ファイル。約1,200。有限。ここが背骨
 *   層2  物語    137窓口 = Sota の一生。型が発火する現場。引き金を型に結ぶ
 *   層3  充填    lifeline/bank/。スロットに入る語彙と定型連鎖。数万。層1の下にぶら下がる
 *
 * ■ trigger(発火条件)が最重要
 * 型を知っていても出てこないのは「いつ撃つか」が紐づいていないから。
 * frame だけ載せた教材は山ほどあって、どれも産出に効かない。
 * **trigger が無い型はこのファイルに入れない。**
 *
 * ■ 進捗の測り方
 * 「何文集めたか」ではなく **「何個の型が、何場面で発火したか」**。
 * 型は有限なので、これは終わりが定義できる指標になる。
 */

/** 型の機能。何をするための型か。会話の目的で切る */
export type PatternFn =
    | 'request'      // 頼む・許可を取る
    | 'offer'        // 申し出る
    | 'refuse'       // 断る・かわす
    | 'confirm'      // 確認する・聞き返す
    | 'opine'        // 意見を出す
    | 'disagree'     // 反対する
    | 'hedge'        // ぼかす・和らげる
    | 'intensify'    // 強める
    | 'narrate'      // 出来事を語る
    | 'evaluate'     // 評価する
    | 'manage'       // 会話を運ぶ(転換・割り込み・締め)
    | 'commit'       // 約束する・引き受ける
    | 'quantify'     // 量と時間を言う
    | 'suppose';     // 仮定する・予測する

/** どれくらい撃つか。core から順に潰す */
export type PatternFreq = 'core' | 'common' | 'edge';

export interface Pattern {
    id: string;
    /** スロット付きの型。[NP] [V] [ADJ] [S] で穴を示す */
    frame: string;
    /** 日本語での機能。訳ではなく「何をする型か」 */
    ja: string;
    fn: PatternFn;
    freq: PatternFreq;
    /**
     * 発火条件。「いつこれを撃つか」。
     * ここが無いと型は死ぬ。frame だけの教材が効かない理由がこれ。
     */
    trigger: string;
    /** スロットに何が入るか。層3(bank)との接続点 */
    slots: string;
    /** 同じ型の実例。最低3。窓口の bank から引いてきてよい */
    examples: string[];
    /** この型が発火する窓口(Station の en)。物語との接続 */
    stations: string[];
    /** 日本語話者がこの型で必ずやること。1行。無ければ省略 */
    trap?: string;
}

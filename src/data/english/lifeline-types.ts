/**
 * THE LIFELINE — 型定義
 *
 * 生まれてから死ぬまでの経験を、全部英語で通す。だから英語が全部揃う。
 * その「全部」を数え上げた単位が **窓口(Station)** である。
 *
 * 設計の柱:
 *   1. 人生は場面ではなく窓口で進む。窓口には必ず定型文がある。教材の本体はそこ。
 *   2. 抜けを作らない。ここに無い経験は、この教材をやっても英語にならない。
 *      品質基準は文の巧拙ではなく、人生に穴が空いていないことである。
 *   3. 各窓口に「日本人がここで必ずやること(trap)」を1つだけ書く。
 *      語彙リストと教材を分けるのはこの1行である。
 *   4. 登場人物は Tonio Town の住人から選ぶ。町民147人 + 職能名簿(lifeline-cast)。
 *
 * ■ 通し番号は持たない
 * 窓口は途中に挿入され続ける。番号を手で書くと挿入のたびに全部ずれる。
 * `no` は幕ファイルの配列順から tonio-lifeline.ts が自動で振る。
 * つまり **配列の順番が人生の順番** である。並べ替えれば人生が変わる。
 */

/**
 * 幕は **課程ではなく棚** である。学習者は既に大人で、語彙も文法も持っている。
 * 習得順(mom → car → 二語文)を再現する意味はゼロ。どこから開いてもいい。
 * 幕が存在する理由は順番ではなく、**抜けを見つけるため**。
 * 「この棚がまだ空だ」が一目でわかることだけが、この分類の仕事である。
 */
export type ActId = 'born' | 'child' | 'high' | 'leave' | 'work' | 'settle' | 'middle' | 'last';

export interface LifePhrase {
    /** 実際に窓口で飛んでくる形。文で持つ。単語では持たない */
    en: string;
    /** 日本語。訳ではなく、その場で言われている内容 */
    ja: string;
    /** なぜこの形なのか。1行。文法用語は使わない */
    note: string;
}

/** 幕ファイルに書く形。番号は書かない */
export interface StationDef {
    act: ActId;
    /** その窓口を通る年齢帯 */
    age: string;
    /** 窓口の名前(英語)。実際に建物やイベントに書いてある呼び方 */
    en: string;
    /** 窓口の名前(日本語) */
    ja: string;
    /** どこで起きるか */
    place: string;
    /** 何が起きるか。1〜2行 */
    what: string;
    /** 日本人がここで必ずやること。1行だけ */
    trap: string;
    /**
     * この窓口で実際に落ちた爆弾。「言ってしまった1文」→「その結果」を1行で。
     * 正解の6文だけ並べると参考書になる。覚えるのは事故の方である。
     * 刃は必ず自分(学習者側)に向ける。窓口の向こうの人を笑い者にしない。
     */
    bomb: string;
    /** 人物 id。requiem-world の147人 + lifeline-cast の職能 */
    cast: string[];
    /** 既に書いてある requiem シナリオ。無ければ空席 */
    built?: { no: string; title: string; key: string };
    /**
     * その窓口の必須6文。ここは増やさない。
     * 「これだけ言えれば通過できる」最小構成であって、表現の総量ではない。
     * 総量は lifeline/bank/ に無制限で積む(目標: 1窓口150前後 × 137窓口 ≒ 2万)。
     */
    phrases: LifePhrase[];
}

/** 組み立て後。no は配列順から自動で振られる */
export interface Station extends StationDef {
    no: number;
}

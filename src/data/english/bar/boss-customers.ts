/** Pick a boss for this night; undefined if conditions not met. */
export function pickBoss(opts: { successSoFar: number; failedSoFar: number; busted: boolean }): Customer | undefined {
    if (opts.busted) return undefined;
    const total = opts.successSoFar + opts.failedSoFar;
    if (total < 4) return undefined; // not enough runway yet
    const rate = total > 0 ? opts.successSoFar / total : 0;
    if (rate < 0.7) return undefined;
    return BOSS_CUSTOMERS[Math.floor(Math.random() * BOSS_CUSTOMERS.length)];
}

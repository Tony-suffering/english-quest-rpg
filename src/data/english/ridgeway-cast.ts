const PROTAGONIST_IDS = new Set(PROTAGONISTS.map((p) => p.id));
const MAJOR_IDS = new Set(MAJORS.map((m) => m.id));

/** 準主要 = 2本以上のシナリオに出ているが、主役/主要に入っていない者 */
export function tierOf(p: WorldPerson): CastTier {
    if (PROTAGONIST_IDS.has(p.id)) return 'protagonist';
    if (MAJOR_IDS.has(p.id)) return 'major';
    if (p.scenarios.length >= 2) return 'supporting';
    return 'ensemble';
}

export function castBreakdown() {
    const counts = { protagonist: 0, major: 0, supporting: 0, ensemble: 0 };
    for (const p of PEOPLE) counts[tierOf(p)]++;
    return counts;
}

export function getProtagonist(id: string): Protagonist | undefined {
    return PROTAGONISTS.find((p) => p.id === id);
}

export function getMajor(id: string): Protagonist | undefined {
    return MAJORS.find((m) => m.id === id);
}

